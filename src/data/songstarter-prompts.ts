// Add lyric-style fragments here. Each one a standalone single-line string.
// The tool treats these exactly like the scenes and fragments above.
export const allusions: string[] = [
  // e.g. "the eggman's been knocking on heaven's door for a while",
];

function allStarters(): string[] {
  return [...scenes, ...fragments, ...allusions];
}

/**
 * Pick a random starter that hasn't been shown yet in the current session.
 * When every starter has been shown, the "seen" set resets and the cycle begins again.
 */
export function pickNext(seen: ReadonlySet<string>): string {
  const all = allStarters();
  if (all.length === 0) return '';
  const unseen = all.filter((s) => !seen.has(s));
  const pool = unseen.length > 0 ? unseen : all;
  return pool[Math.floor(Math.random() * pool.length)];
}

export function totalCount(): number {
  return allStarters().length;
}
