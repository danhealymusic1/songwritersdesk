// Collision pool: short motifs only (titleSeeds + fragments).
// Scenes are long and already complete prompts, so they surface solo only.
function collisionPool(): string[] {
  return [...titleSeeds, ...fragments];
}

// Connectors used to glue two random seeds together.
const CONNECTORS: string[] = [
  "like", "like a", "as", "as a", "to", "into", "through",
  "under", "over", "beside", "with", "without", "against",
  "next to", "behind", "past", "after", "before",
  "and", "but", "meets",
  ",", "—", ":",
];

function pick<T>(arr: readonly T[]): T {
  return arr[Math.floor(Math.random() * arr.length)];
}

function lowerFirst(s: string): string {
  return s.length > 0 ? s.charAt(0).toLowerCase() + s.slice(1) : s;
}

/**
 * Pick a random output.
 *   - 15% of the time: a solo scene (already a complete prompt).
 *   - 85% of the time: collide two short seeds with a random connector.
 *
 * The `seen` parameter is accepted for backward compatibility but the
 * space of possible collisions is large enough to be effectively unrepeating.
 */
export function pickNext(_seen: ReadonlySet<string>): string {
  // 15% of the time, surface a solo scene as-is.
  if (Math.random() < 0.15 && scenes.length > 0) {
    return pick(scenes);
  }

  const pool = collisionPool();
  if (pool.length < 2) return pool[0] ?? '';

  const a = pick(pool);
  let b = pick(pool);
  for (let i = 0; i < 5 && b === a; i++) b = pick(pool);

  // Strip trailing periods before gluing, and lowercase the second half.
  const aClean = a.replace(/\.$/, '');
  const bClean = lowerFirst(b.replace(/\.$/, ''));

  const c = pick(CONNECTORS);
  if (c === ',' || c === ':' || c === '—') {
    return `${aClean}${c} ${bClean}`;
  }
  return `${aClean} ${c} ${bClean}`;
}

export function totalCount(): number {
  return collisionPool().length * CONNECTORS.length;
}
